-- ---------------------------------------------------------------------
-- 胜场 / 负场初始化（FR-11 的初始值）
-- 直接从已结束比赛（status='F'）推导，避免手工统计出错：
--   盘分形如 2:1，冒号前为 team_no=1 的盘数，前 > 后即 1 队胜，否则 2 队胜；
--   双打/混双的 2 名同队选手分别累加一次，与成绩录入时的累加口径一致。
-- ---------------------------------------------------------------------
UPDATE `player` p
JOIN (
    SELECT
        mp.player_id,
        SUM(CASE
                WHEN (mp.team_no = 1 AND CAST(SUBSTRING_INDEX(m.set_score, ':', 1) AS UNSIGNED)
                                      > CAST(SUBSTRING_INDEX(m.set_score, ':', -1) AS UNSIGNED))
                  OR (mp.team_no = 2 AND CAST(SUBSTRING_INDEX(m.set_score, ':', 1) AS UNSIGNED)
                                      < CAST(SUBSTRING_INDEX(m.set_score, ':', -1) AS UNSIGNED))
                THEN 1 ELSE 0
            END) AS win_cnt,
        SUM(CASE
                WHEN (mp.team_no = 1 AND CAST(SUBSTRING_INDEX(m.set_score, ':', 1) AS UNSIGNED)
                                      < CAST(SUBSTRING_INDEX(m.set_score, ':', -1) AS UNSIGNED))
                  OR (mp.team_no = 2 AND CAST(SUBSTRING_INDEX(m.set_score, ':', 1) AS UNSIGNED)
                                      > CAST(SUBSTRING_INDEX(m.set_score, ':', -1) AS UNSIGNED))
                THEN 1 ELSE 0
            END) AS loss_cnt
    FROM `match` m
    JOIN `match_player` mp ON mp.match_id = m.match_id
    WHERE m.status = 'F' AND m.set_score IS NOT NULL
    GROUP BY mp.player_id
) t ON t.player_id = p.player_id
SET p.win_count = t.win_cnt, p.loss_count = t.loss_cnt;
